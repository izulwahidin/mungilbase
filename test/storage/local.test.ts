import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { LocalStorage } from '../../src/storage/local.js'

const key = 'posts/0123456789abcdef/avatar/123e4567-e89b-12d3-a456-426614174000.png'
let dir: string
let storage: LocalStorage

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), 'mungil-files-'))
  storage = new LocalStorage(dir)
})

afterEach(() => {
  rmSync(dir, { recursive: true, force: true })
})

describe('LocalStorage', () => {
  it('stores and returns data with metadata', async () => {
    const data = Buffer.from('hello file')
    await storage.put(key, data, 'image/png', 'pic.png')

    const stored = await storage.get(key)
    expect(stored?.contentType).toBe('image/png')
    expect(stored?.filename).toBe('pic.png')
    expect(stored?.data.equals(data)).toBe(true)
  })

  it('deletes the data and metadata', async () => {
    await storage.put(key, Buffer.from('x'), 'text/plain', 'x.txt')
    await storage.delete(key)
    expect(await storage.get(key)).toBeNull()
  })

  it('returns null for missing files', async () => {
    expect(await storage.get(key)).toBeNull()
  })

  it('rejects keys that are not generated by the upload route', async () => {
    for (const bad of [
      '../../etc/passwd',
      'posts/0123456789abcdef/avatar/../../x.png',
      'Posts/0123456789abcdef/avatar/x.png',
      'posts/nothex/avatar/x.png',
      'posts/0123456789abcdef/avatar/x',
    ]) {
      await expect(storage.put(bad, Buffer.from('x'), 'text/plain', 'x')).rejects.toThrow(
        /Invalid storage key/,
      )
    }
  })
})
